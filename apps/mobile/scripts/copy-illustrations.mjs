#!/usr/bin/env node
// Copies the Agnes illustrations the app uses from design/mocks/assets into assets/illustrations
// (the seed pack's art, TRD §3.2), with their alt text and licence from the mock manifest, and
// writes src/seed/illustrations.ts. Run after changing ILLUSTRATIONS. Never draw art here.
import { copyFileSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const app = join(here, '..');
const src = join(app, '..', '..', 'design', 'mocks', 'assets');
const dst = join(app, 'assets', 'illustrations');

const manifest = JSON.parse(readFileSync(join(src, 'manifest.json'), 'utf8'));
const byFile = new Map(manifest.images.map((i) => [i.file, i]));

const pets = ['base', 'celebrate', 'proud', 'wave', 'thinking', 'sleepy', 'worried', 'resting'];
const ILLUSTRATIONS = [
  ...pets.map((p) => `cat-${p}`),
  'cat-plant', 'cat-watering', 'cat-price-tag', 'cat-shield-key', 'cat-reading',
  ...pets.filter((p) => p !== 'proud').map((p) => `dog-${p}`),
  'plant-seed', 'plant-sprout', 'plant-sapling', 'plant-flowering', 'plant-tree',
  'plant-sapling-droopy', 'plant-sapling-dry', 'plant-sapling-wilted', 'plant-sapling-dormant',
  'scene-welcome', 'scene-lesson-complete', 'scene-paywall', 'scene-exam-goal', 'scene-student-laptop',
  'ui-all-caught-up', 'ui-offline', 'ui-signin-saved', 'ui-notify-bell', 'ui-search-empty', 'ui-language-hello',
  'subject-physics', 'subject-chemistry', 'subject-maths', 'subject-biology', 'subject-polity', 'subject-history',
  'lab-circuit', 'lab-optics', 'lab-titration',
  'object-gems', 'water-cup', 'badge-first-lesson', 'logo-mark',
];

const meta = {};
for (const name of ILLUSTRATIONS) {
  const file = `${name}.webp`;
  const m = byFile.get(file);
  if (!m) throw new Error(`${file} is not in the mock manifest`);
  copyFileSync(join(src, file), join(dst, file));
  meta[name] = { alt: m.alt ?? null, licence: m.licence ?? 'owned', source: m.source ?? 'agnes', status: m.status ?? 'draft' };
}
writeFileSync(join(dst, 'illustrations.json'), JSON.stringify(meta, null, 2) + '\n');

const lines = [
  '// Generated by apps/mobile/scripts/copy-illustrations.mjs. Do not edit.',
  '// Agnes illustrations bundled with the app (seed pack art). Licence and alt text: assets/illustrations/illustrations.json.',
  'import type { ImageSourcePropType } from "react-native";',
  '',
  'export const bundledIllustrations: Record<string, ImageSourcePropType> = {',
  ...ILLUSTRATIONS.map((n) => `  ${JSON.stringify(n)}: require(${JSON.stringify(`../../assets/illustrations/${n}.webp`)}),`),
  '};',
  '',
];
writeFileSync(join(app, 'src', 'seed', 'illustrations.ts'), lines.join('\n'));
console.log(`copied ${ILLUSTRATIONS.length} illustrations`);
