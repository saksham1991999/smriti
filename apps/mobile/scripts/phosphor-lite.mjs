#!/usr/bin/env node
// Writes src/shims/phosphor-lite.generated.ts: only the Phosphor icons the app's packages import,
// each from its own module. metro.config.cjs points `phosphor-react-native` there, because the
// package root re-exports every icon (about 5.7 MB of source) and Metro does not tree-shake.
// `--check` fails when the file is out of date (run by the lint script and the Jest suite).
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..', '..');
const out = join(here, '..', 'src', 'shims', 'phosphor-lite.generated.ts');
const importers = ['packages/ui-native/src/components/Icon.tsx', 'packages/ui-native/src/components/SignInButtons.tsx'];

const names = new Set();
for (const rel of importers) {
  const file = join(root, rel);
  if (!existsSync(file)) continue;
  const src = readFileSync(file, 'utf8');
  for (const m of src.matchAll(/import\s*\{([^}]*)\}\s*from\s*["']phosphor-react-native["']/g)) {
    for (const part of m[1].split(',')) {
      const name = part.trim().replace(/^type\s+/, '').split(/\s+as\s+/)[0]?.trim();
      if (name && /Icon$/.test(name) && !part.trim().startsWith('type ')) names.add(name);
    }
  }
}
const sorted = [...names].sort();
const body = [
  '/* GENERATED by scripts/phosphor-lite.mjs: the Phosphor icons ui-native imports, one module each. */',
  '// Bundled only through metro.config.cjs (ui-native owns the dependency and its types); tsconfig',
  '// excludes it, since it would type-check Phosphor\'s own sources.',
  ...sorted.map((n) => `export { ${n} } from 'phosphor-react-native/src/icons/${n.slice(0, -4)}';`),
  "export type { Icon, IconProps, IconWeight } from 'phosphor-react-native';",
  '',
].join('\n');

if (process.argv.includes('--check')) {
  const current = existsSync(out) ? readFileSync(out, 'utf8') : '';
  if (current !== body) {
    console.error('phosphor-lite: src/shims/phosphor-lite.generated.ts is out of date; run node scripts/phosphor-lite.mjs');
    process.exit(1);
  }
  console.log(`phosphor-lite: ok (${sorted.length} icons)`);
} else {
  writeFileSync(out, body);
  console.log(`phosphor-lite: ${sorted.length} icons -> ${out}`);
}
