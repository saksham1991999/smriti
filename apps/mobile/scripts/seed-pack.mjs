#!/usr/bin/env node
// Copies the published seed pack into the app (TRD §3.2: "each variant's build includes a small
// seed pack") and writes src/seed/generated/index.ts, which require()s every file so Metro bundles
// them. Source: tools/content-publish/out/seed/<variant>/<locale>/ from
// `pnpm --filter @smriti/content-publish publish:fixtures` (or the real publish job).
//
// SEED_VARIANT picks the pack (default: APP_VARIANT when the publish output has it, else `fx`,
// the fixture pack used in dev and tests). The output folder is generated and git-ignored.
import { execFileSync } from 'node:child_process';
import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const app = join(here, '..');
const root = join(app, '..', '..');
const outRoot = join(root, 'tools', 'content-publish', 'out', 'seed');
const target = join(app, 'src', 'seed', 'generated');
const LOCALES = ['en', 'hi'];

if (!existsSync(outRoot)) {
  console.log('seed-pack: no publish output yet, running publish:fixtures');
  execFileSync('pnpm', ['--filter', '@smriti/content-publish', 'publish:fixtures'], { cwd: root, stdio: 'inherit' });
}

const available = readdirSync(outRoot).filter((d) => statSync(join(outRoot, d)).isDirectory());
const wanted = process.env.SEED_VARIANT ?? process.env.APP_VARIANT;
const variant = wanted && available.includes(wanted) ? wanted : available.includes('fx') ? 'fx' : available[0];
if (!variant) throw new Error(`seed-pack: nothing under ${outRoot}`);

const stamp = join(target, '.source');
const sourceKey = `${variant}:${LOCALES.map((l) => readFileSync(join(outRoot, variant, l, 'seed-pack.json'), 'utf8').length).join(',')}`;
if (existsSync(stamp) && readFileSync(stamp, 'utf8') === sourceKey && existsSync(join(target, 'index.ts'))) {
  process.exit(0);
}

rmSync(target, { recursive: true, force: true });
mkdirSync(target, { recursive: true });

const lines = [
  '// Generated by apps/mobile/scripts/seed-pack.mjs. Do not edit.',
  `// Seed pack variant: ${variant}.`,
  '/* eslint-disable */',
  'import type { SeedPackFiles } from "../types";',
  '',
  'export const SEED_VARIANT = ' + JSON.stringify(variant) + ';',
  '',
  'export const seedPacks: Record<"en" | "hi", SeedPackFiles> = {',
];

for (const locale of LOCALES) {
  const src = join(outRoot, variant, locale);
  const dst = join(target, locale);
  cpSync(src, dst, { recursive: true });
  const pack = JSON.parse(readFileSync(join(dst, 'seed-pack.json'), 'utf8'));
  const rel = (p) => './' + relative(target, join(dst, p)).split('\\').join('/');
  lines.push(`  ${locale}: {`);
  lines.push(`    pack: require(${JSON.stringify(rel('seed-pack.json'))}),`);
  lines.push('    manifests: {');
  for (const m of pack.manifests) lines.push(`      ${JSON.stringify(m.path)}: () => require(${JSON.stringify(rel(m.path))}),`);
  lines.push('    },');
  lines.push('    bundles: {');
  for (const b of pack.bundles) lines.push(`      ${JSON.stringify(b.path)}: () => require(${JSON.stringify(rel(b.path))}),`);
  lines.push('    },');
  lines.push('    assets: {');
  const assetsDir = join(dst, 'assets');
  if (existsSync(assetsDir)) {
    for (const f of readdirSync(assetsDir).sort()) lines.push(`      ${JSON.stringify('assets/' + f)}: require(${JSON.stringify(rel('assets/' + f))}),`);
  }
  lines.push('    },');
  lines.push('  },');
}
lines.push('};', '');
writeFileSync(join(target, 'index.ts'), lines.join('\n'));
writeFileSync(stamp, sourceKey);
console.log(`seed-pack: copied ${variant} (${LOCALES.join(', ')}) into src/seed/generated`);
