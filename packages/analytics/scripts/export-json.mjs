// Writes catalogue.json: the event catalogue plus the policy and guard lists, for the API's
// `POST /v1/analytics/events` (apps/api/smriti_api/services/analytics_ingest.py), so the server
// checks events exactly as this package does. Node strips the TypeScript types.
//
//   node scripts/export-json.mjs [--check]
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

export const CATALOGUE_JSON = 'catalogue.json';

export async function catalogueDocument() {
  const { CATALOGUE } = await import('../src/catalogue.generated.ts');
  const policy = await import('../src/policy.ts');
  const guard = await import('../src/guard.ts');
  return {
    version: 1,
    note: 'Generated by scripts/export-json.mjs from src/. Do not edit by hand.',
    policy: {
      little_learner_product_allowlist: [...policy.LITTLE_LEARNER_PRODUCT_ALLOWLIST],
      minor_stripped_props: [...policy.MINOR_STRIPPED_PROPS],
    },
    guard: {
      pii_prop_names: [...guard.PII_PROP_NAMES],
      ad_id_prop_names: [...guard.AD_ID_PROP_NAMES],
      max_list_items: 50,
    },
    events: CATALOGUE,
  };
}

async function main() {
  const out = join(dirname(fileURLToPath(import.meta.url)), '..', CATALOGUE_JSON);
  const text = `${JSON.stringify(await catalogueDocument(), null, 2)}\n`;
  if (process.argv.includes('--check')) {
    if (!existsSync(out) || readFileSync(out, 'utf8') !== text) {
      console.error(`out of date: ${out} (run pnpm --filter @smriti/analytics generate)`);
      process.exit(1);
    }
    return;
  }
  writeFileSync(out, text);
  console.log(`wrote ${out}`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) await main();
