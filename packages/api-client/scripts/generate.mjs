// Regenerates openapi.json from apps/api's Pydantic models and src/schema.ts from it.
//   node scripts/generate.mjs           write both files
//   node scripts/generate.mjs --check   fail when either file is out of date (for CI)
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import openapiTS, { astToString } from "openapi-typescript";
import * as prettier from "prettier";

const here = dirname(fileURLToPath(import.meta.url));
const pkg = join(here, "..");
const apiDir = join(pkg, "..", "..", "apps", "api");
const check = process.argv.includes("--check");

const spec = execFileSync("uv", ["run", "--quiet", "python", "-m", "smriti_api.openapi"], {
  cwd: apiDir,
  encoding: "utf8",
  env: { ...process.env, APP_ENV: process.env.APP_ENV ?? "local" },
});
const doc = JSON.parse(spec);
const ast = await openapiTS(doc, { alphabetize: true });
const banner =
  "// Generated by scripts/generate.mjs from apps/api (Pydantic models). Do not edit by hand.\n" +
  "// Run `pnpm --filter @smriti/api-client generate` after changing the API.\n\n";

// Formatted with the repo's Prettier config, so `prettier --check .` passes on generated files.
const jsonFile = join(pkg, "openapi.json");
const tsFile = join(pkg, "src", "schema.ts");
const format = async (text, file) =>
  prettier.format(text, { ...(await prettier.resolveConfig(file)), filepath: file });
const outputs = [
  [jsonFile, await format(JSON.stringify(doc), jsonFile)],
  [tsFile, await format(`${banner}${astToString(ast)}`, tsFile)],
];
let stale = false;
for (const [file, text] of outputs) {
  let current = "";
  try {
    current = readFileSync(file, "utf8");
  } catch {
    current = "";
  }
  if (current === text) continue;
  if (check) {
    console.error(`out of date: ${file}`);
    stale = true;
  } else {
    writeFileSync(file, text);
    console.log(`wrote ${file}`);
  }
}
if (stale) {
  console.error("Run `pnpm --filter @smriti/api-client generate` and commit the result.");
  process.exit(1);
}
