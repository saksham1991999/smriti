#!/usr/bin/env node
/**
 * Builds `dist/index.js`: `src/` as one plain ESM file (variant JSON inlined, zod external), so
 * plain Node can import `@smriti/config` (Expo's app.config.ts, node scripts). TypeScript-aware
 * consumers (tsc, Vite/Vitest, Metro, Jest) keep reading `src/` through the `exports` conditions.
 *
 *   node scripts/build.mjs           build
 *   node scripts/build.mjs --check   exit 1 when dist/index.js is missing or out of date
 */
import { existsSync, readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { build } from 'esbuild';

const pkg = join(dirname(fileURLToPath(import.meta.url)), '..');
const outfile = join(pkg, 'dist', 'index.js');
const check = process.argv.includes('--check');

const options = {
  entryPoints: [join(pkg, 'src', 'index.ts')],
  bundle: true,
  format: 'esm',
  platform: 'node',
  target: 'node20',
  external: ['zod'],
  legalComments: 'none',
  banner: { js: '// Generated by packages/config/scripts/build.mjs from src/. Do not edit.' },
  logLevel: 'warning',
};

if (check) {
  const res = await build({ ...options, write: false, outfile });
  const fresh = res.outputFiles?.[0]?.text ?? '';
  const current = existsSync(outfile) ? readFileSync(outfile, 'utf8') : null;
  if (current !== fresh) {
    console.error('packages/config/dist/index.js is missing or stale: run `pnpm --filter @smriti/config build`');
    process.exit(1);
  }
} else {
  await build({ ...options, outfile });
}
