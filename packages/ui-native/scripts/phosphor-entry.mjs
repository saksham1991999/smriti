#!/usr/bin/env node
// Writes src/components/phosphor.js and phosphor.d.ts: the Phosphor icons ui-native uses, each
// imported from its own module (`phosphor-react-native/src/icons/<Name>`, an export the package
// declares). The package root re-exports every icon, about 5.7 MB of source, and Metro does not
// tree-shake, so importing the root put all of them in every app bundle.
//
// The .js file is what Metro and Jest load. The .d.ts takes the types from the package root,
// because type-checking Phosphor's .tsx sources fails under strict settings.
//
// The names are @smriti/tokens/ui iconNames plus EXTRA (icons used directly, not through <Icon>).
// `--check` fails when either file is out of date (run by `pnpm lint` and a test).
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const pkg = join(here, "..");
const tokensIcons = join(pkg, "..", "tokens", "src", "ui", "icons.ts");
const EXTRA = ["AppleLogo"];

const list = readFileSync(tokensIcons, "utf8").match(/iconNames\s*=\s*\[([\s\S]*?)\]\s*as const/);
if (!list) throw new Error("phosphor-entry: could not read iconNames from @smriti/tokens/src/ui/icons.ts");
const names = [...new Set([...[...list[1].matchAll(/"([A-Za-z]+)"/g)].map((m) => m[1]), ...EXTRA])].sort();

const header = "/* GENERATED by scripts/phosphor-entry.mjs from @smriti/tokens/ui iconNames. Do not edit. */";
const js = [header, ...names.map((n) => `export { ${n}Icon } from "phosphor-react-native/src/icons/${n}";`), ""].join("\n");
const dts = [header, `export { ${names.map((n) => `${n}Icon`).join(", ")} } from "phosphor-react-native";`, ""].join("\n");

const outputs = [
  [join(pkg, "src", "components", "phosphor.js"), js],
  [join(pkg, "src", "components", "phosphor.d.ts"), dts],
];

if (process.argv.includes("--check")) {
  const stale = outputs.filter(([file, body]) => !existsSync(file) || readFileSync(file, "utf8") !== body);
  if (stale.length > 0) {
    console.error(`phosphor-entry: out of date, run node scripts/phosphor-entry.mjs (${stale.map(([f]) => f).join(", ")})`);
    process.exit(1);
  }
  console.log(`phosphor-entry: ok (${names.length} icons)`);
} else {
  for (const [file, body] of outputs) writeFileSync(file, body);
  console.log(`phosphor-entry: ${names.length} icons`);
}
