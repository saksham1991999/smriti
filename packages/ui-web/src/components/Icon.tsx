export interface IconProps extends IconContract {
  className?: string;
}

/** A Phosphor icon. Decorative (aria-hidden) unless it has a `label`. */
export function Icon({ name, size = 24, weight = "bold", color, label, className, testID }: IconProps) {
  const C = iconMap[name];
  return (
    <C
      size={size}
      weight={weight}
      data-testid={testID}
      className={cx("shrink-0", color && colorClass[color], className)}
      aria-hidden={label ? undefined : true}
      aria-label={label}
      role={label ? "img" : undefined}
      focusable="false"
    />
  );
}
