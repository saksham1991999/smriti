#!/usr/bin/env node
// Writes docs/SCREENS.md: every screen ID in docs/ux/*.md with its name, phase and mock priority.
//   node tools/docs/screen_index.mjs          (write)
//   node tools/docs/screen_index.mjs --check  (exit 1 if SCREENS.md is stale or an ID is duplicated)

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const areas = [
  ["onboarding", "Entry and onboarding", ["ENT", "ONB"]],
  ["auth", "Sign-in and accounts", ["AUTH"]],
  ["learn", "Home, learning and lessons", ["HOME", "LRN", "LES"]],
  ["memory-labs", "Memory tools and labs", ["MEM", "LAB"]],
  ["practice", "Practice and mock tests", ["PRC", "MOCK"]],
  ["tutor-social", "AI tutor and friends", ["AI", "SOC"]],
  ["me-money", "Me, settings, Pro and notifications", ["ME", "SET", "PAY", "NTF"]],
];

const seen = new Map();
let out = `# Smriti — Screen index

Generated by \`node tools/docs/screen_index.mjs\` from the screen specs in \`docs/ux/\`. Don't edit by hand.

Every screen has one ID. Flows live in \`docs/flows/<area>.md\`, and each screen's full spec (layout, copy in English and Hindi, states, motion, accessibility, analytics, web layout) is in \`docs/ux/<area>.md\`. "P0" screens are drawn in the visual mocks (\`design/mocks/\`). Phase 1 unless marked.

`;
let total = 0;
for (const [file, title, prefixes] of areas) {
  const path = join(root, "docs", "ux", `${file}.md`);
  if (!existsSync(path)) continue;
  const lines = readFileSync(path, "utf8").split("\n");
  const rows = [];
  for (let i = 0; i < lines.length; i++) {
    const m = lines[i].match(/^### ([A-Z]+-\d+) · (.+)$/);
    if (!m || !prefixes.includes(m[1].split("-")[0])) continue;
    const [, id, rawName] = m;
    // Look ahead in this block for the mock priority / phase line.
    let prio = "", phase = "";
    for (let j = i + 1; j < lines.length && !lines[j].startsWith("### "); j++) {
      const p = lines[j].match(/\*\*Mock priority:\*\*\s*\**(P\d)/);
      if (p && !prio) prio = p[1];
      // Phase is either "**Phase:** N" or "· Phase N" on the priority line.
      const ph = lines[j].match(/(?:\*\*Phase:\*\*\s*|· Phase\s*)(\d)/);
      if (ph && !phase) phase = ph[1];
    }
    const nameParts = rawName.split(" · ");
    const name = nameParts[0];
    const titlePhase = (rawName.match(/Phase (\d)/) || [])[1];
    if (titlePhase) phase = titlePhase;
    if (seen.has(id)) { console.error(`Duplicate ID ${id} in ${file} and ${seen.get(id)}`); process.exitCode = 1; }
    seen.set(id, file);
    rows.push(`| ${id} | ${name.replace(/\|/g, "/")} | ${phase && phase !== "1" ? phase : ""} | ${prio} |`);
  }
  total += rows.length;
  out += `## ${title}\n\nFlow: [\`docs/flows/${file}.md\`](flows/${file}.md) · Specs: [\`docs/ux/${file}.md\`](ux/${file}.md) · ${rows.length} screens\n\n| ID | Screen | Phase | Mock |\n|---|---|---|---|\n${rows.join("\n")}\n\n`;
}
out = out.replace("Phase 1 unless marked.", `Phase 1 unless marked. ${total} screens in total.`);

const target = join(root, "docs", "SCREENS.md");
if (process.argv.includes("--check")) {
  const cur = existsSync(target) ? readFileSync(target, "utf8") : "";
  if (cur !== out) { console.error("docs/SCREENS.md is stale. Run node tools/docs/screen_index.mjs"); process.exit(1); }
} else {
  writeFileSync(target, out);
  console.log(`docs/SCREENS.md: ${total} screens`);
}
